def rect_area(r):
    return (r[2] - r[0]) * (r[3] - r[1])


def room_area(room):
    return sum(rect_area(r) for r in room["rects"])


def floor_area(floor):
    return sum(room_area(r) for r in ROOMS[floor])


def perimeter_ext():
    return 2 * (FOOTPRINT_W + FOOTPRINT_D)


def window_area(side_filter=None):
    a = 0.0
    for fl in (1, 2):
        for s, a1, a2, h, sill, tag in WINDOWS[fl]:
            if side_filter and s != side_filter:
                continue
            a += (a2 - a1) * h
    return a


def ext_door_area():
    return sum((a2 - a1) * h for fl in (1, 2) for s, a1, a2, h, tag, kind in EXT_DOORS[fl])


