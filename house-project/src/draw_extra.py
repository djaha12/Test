class Iso:
    def __init__(self, sh, ox, oy, k):
        self.s, self.ox, self.oy, self.k = sh, ox, oy, k
        self.c = math.cos(math.radians(30)); self.si = math.sin(math.radians(30))

    def P(self, x, y, z):
        return (self.ox + (x - y) * self.c * self.k, self.oy - (z + (x + y) * self.si) * self.k)

    def line(self, p1, p2, **kw):
        X1, Y1 = self.P(*p1); X2, Y2 = self.P(*p2)
        self.s.pline(X1, Y1, X2, Y2, **kw)

    def poly(self, pts, **kw):
        self.s.ppoly([self.P(*p) for p in pts], **kw)

    def text(self, p, t, dx=0, dy=0, **kw):
        X, Y = self.P(*p)
        self.s.ptext(X + dx, Y + dy, t, **kw)

    def dot(self, p, r=0.9, color="#000"):
        X, Y = self.P(*p)
        self.s.pcircle(X, Y, r, fill=color, stroke=None)


