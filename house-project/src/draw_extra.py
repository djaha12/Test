def wall_chain(v, rect, doors, off=7):
    x1, y1, x2, y2 = rect
    horiz = (x2 - x1) >= (y2 - y1)
    pts = set()
    if horiz:
        pts |= {x1, x2}
        for d in doors:
            dx1, dy1, dx2, dy2 = d["rect"]
            if dy1 >= y1 - 1e-3 and dy2 <= y2 + 1e-3 and dx1 >= x1 - 1e-3 and dx2 <= x2 + 1e-3:
                pts |= {dx1, dx2}
        v.dim_h(sorted(pts), y1, -off, text_size=1.7, ext_from=y1)
    else:
        pts |= {y1, y2}
        for d in doors:
            dx1, dy1, dx2, dy2 = d["rect"]
            if dx1 >= x1 - 1e-3 and dx2 <= x2 + 1e-3 and dy1 >= y1 - 1e-3 and dy2 <= y2 + 1e-3:
                pts |= {dy1, dy2}
        v.dim_v(sorted(pts), x2, off, text_size=1.7, ext_from=x2)


