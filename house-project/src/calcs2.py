def extra_struct():
    B = R["beam"]
    E = {}
    q_n = B["q"] / 1.18
    Lb = B["L"]
    I = 0.25 * 0.7 ** 3 / 12
    Eb = 30e6   # кПа
    EI = Eb * I * 0.35   # с учётом трещин и ползучести (ψ ≈ 0,35)
    f = 5 * q_n * Lb ** 4 / (384 * EI)
    E["beam"] = {"q_n": q_n, "L": Lb, "I": I, "EI_eff": EI, "f_mm": f * 1000, "lim250": Lb / 250 * 1000, "lim500": Lb / 500 * 1000}
    # фронтон: D500 300 мм, высота 3,75 м, опирание по низу (плита) и по скату (прогоны/стропила)
    w0 = CLIMATE["w_0"]
    w = w0 * 0.75 * (0.8 + 0.3) * 1.4   # напор + внутреннее разрежение
    h = ROOF["ridge_z"] - 6.5 - 0.28
    M = w * h ** 2 / 8
    W = 1.0 * 0.3 ** 2 / 6
    sigma = M / W    # кПа
    N_self = 5.2 * 0.3 * h / 2   # кН/м на середине высоты
    sigma_c = N_self / 0.3
    E["gable"] = {"w_kPa": w, "h": h, "M": M, "sigma_kPa": sigma, "sigma_c_kPa": sigma_c, "R_tb_kPa": 90.0, "ok": sigma - sigma_c <= 90}
    # тяга естественной вентиляции при t_н = +5 °С (СП 60) и +15 °С
    def draft(h_m, t_out):
        rho_out = 353 / (273 + t_out)
        rho_in = 353 / (273 + 20)
        return h_m * 9.81 * (rho_out - rho_in)
    def loss(L_m3h, d_mm, L_m, zeta=4.5):
        d = d_mm / 1000
        A = math.pi * d * d / 4
        v = L_m3h / 3600 / A
        return (0.02 * L_m / d + zeta) * 1.2 * v * v / 2, v
    cases = []
    for name, L, d, hgt in (("В3 санузел 1 эт. (25 м³/ч, Ø125)", 25, 125, 8.5), ("В5 санузел мастер 2 эт. (25 м³/ч, Ø125)", 25, 125, 5.0),
                            ("В4 кухня естеств. (60 м³/ч, Ø160)", 60, 160, 8.5), ("В4 кухня естеств. (60 м³/ч, Ø125) — для сравнения", 60, 125, 8.5),
                            ("В1 котельная (50 м³/ч, Ø125)", 50, 125, 9.0)):
        dp5 = draft(hgt, 5.0); dp15 = draft(hgt, 15.0)
        dl, v = loss(L, d, hgt)
        cases.append({"name": name, "h": hgt, "dp5": dp5, "dp15": dp15, "loss": dl, "v": v, "ok5": dp5 >= dl, "ok15": dp15 >= dl})
    E["draft"] = cases
    return E


