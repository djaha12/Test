def lighting():
    Lg = []
    norms = {"Гостиная": 200, "Кухня": 200, "Кабинет": 300, "Спальня": 150, "Холл": 150, "Прихожая": 100, "Тамбур": 75, "Коридор": 75,
             "Санузел": 100, "Ванная": 100, "Постирочная": 150, "Гардероб": 75, "Гардеробная": 100, "Кладовая": 50, "Бельевая": 75,
             "Котельная": 100, "Гараж": 100, "Хозяйственная": 150, "Лестничный": 100, "Прихожая спальни": 75}
    lum = {"down": ("LED-даунлайт 12 Вт / 1100 лм, 4000 K", 12, 1100), "panel": ("LED-панель 36 Вт / 3600 лм", 36, 3600)}
    total_W = 0
    total_n = 0
    for fl in (1, 2):
        for r in ROOMS[fl]:
            E = next((v for k, v in norms.items() if r["name"].startswith(k)), 100)
            a = room_area(r)
            eta = 0.55 if a > 12 else 0.45
            kz = 1.2
            key = "panel" if (a > 20 and "Гостиная" not in r["name"] and "Спальня" not in r["name"]) else "down"
            name, W, lm = lum[key]
            n = math.ceil(E * a * kz / (lm * eta))
            n = max(n, 1)
            Lg.append({"n": r["n"], "name": r["name"], "area": a, "E": E, "lum": name, "count": n, "W": n * W, "Wm2": n * W / a})
            total_W += n * W; total_n += n
    return {"rooms": Lg, "total_W": total_W, "total_n": total_n, "Wm2": total_W / S["area_total"]}


