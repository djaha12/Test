def dp_pipe(Q_m3h, d_in_mm, L_m, nu=1.0e-6, rho=1000.0, zeta=0.0):
    """Потери давления, Па (Дарси–Вейсбах, Колбрук упрощённо для пластика k=0,007 мм)"""
    d = d_in_mm / 1000
    A = math.pi * d * d / 4
    v = Q_m3h / 3600 / A
    Re = v * d / nu
    if Re < 2300:
        lam = 64 / max(Re, 1)
    else:
        lam = 0.11 * (0.007e-3 / d + 68 / Re) ** 0.25   # Альтшуль
    dp = (lam * L_m / d + zeta) * rho * v * v / 2
    return v, Re, lam, dp


def hydraulics():
    Hy = {}
    H = R["heating"]
    # --- тёплый пол: петля 100 м PE-Xa 16×2,0 (d_in 12), Δt = 7 K
    loops = []
    for l in H["ufh"]:
        q = next(x for x in H["rooms"] if x["n"] == l["n"])["Q_W"] / l["loops"]
        L = l["length"] / l["loops"]
        G = q / (4190 * 7) * 3600 / 1000   # м³/ч
        v, Re, lam, dp = dp_pipe(G, 12.0, L, nu=0.66e-6, rho=992, zeta=10)
        loops.append({"n": l["n"], "name": l["name"], "q_W": q, "L": L, "G_lh": G * 1000, "v": v, "dp_kPa": dp / 1000})
    Hy["loops"] = loops
    worst = max(loops, key=lambda x: x["dp_kPa"])
    Hy["loop_worst"] = worst
    Hy["pump_ufh"] = {"Q_m3h": sum(x["G_lh"] for x in loops if x["n"].startswith("1.")) / 1000, "H_kPa": worst["dp_kPa"] + 15,
                      "note": "насос 25-60 (H = 6 м) на каждом смесительном узле, расходомеры 0–4 л/мин"}
    # магистраль котёл → гидрострелка → коллекторы: Δt = 15 K (первичный контур 60/45)
    Q = H["Q_total"] * 1000
    G_main = Q / (4190 * 15) * 3600 / 1000
    v32, Re32, lam32, dp32 = dp_pipe(G_main, 21.2, 40, nu=0.5e-6, rho=983, zeta=15)
    v25, _, _, dp25 = dp_pipe(G_main * 0.55, 16.6, 12, nu=0.5e-6, rho=983, zeta=8)
    Hy["main"] = {"G_m3h": G_main, "d": "PP-R 32 (d_in 21,2)", "v": v32, "dp_kPa": dp32 / 1000, "riser_v": v25, "riser_dp": dp25 / 1000}
    # --- водоснабжение
    Wt = R["water"]
    q_s = Wt["q_s"]   # л/с
    v_in, _, _, dp_in = dp_pipe(q_s * 3.6, 26.2, 25, zeta=8)    # ПНД 32 SDR11 d_in 26,2
    v_coll, _, _, dp_coll = dp_pipe(q_s * 3.6, 21.2, 10, zeta=10)   # PP-R 32 к коллектору
    fixtures = [("Умывальник", 0.10, 12.0), ("Унитаз (инсталляция)", 0.10, 12.0), ("Душ", 0.12, 12.0), ("Ванна", 0.25, 16.0),
                ("Мойка кухонная", 0.12, 12.0), ("Стиральная машина", 0.12, 12.0), ("Поливочный кран", 0.30, 16.0)]
    fx = []
    for name, q, din in fixtures:
        v, _, _, dp = dp_pipe(q * 3.6, din, 15, zeta=6)
        fx.append({"name": name, "q": q, "pipe": f"PEX {'16×2,0' if din == 12 else '20×2,0'}", "v": v, "dp_kPa": dp / 1000})
    Hy["water"] = {"q_s": q_s, "v_in": v_in, "dp_in_kPa": dp_in / 1000, "v_coll": v_coll, "dp_coll_kPa": dp_coll / 1000, "fixtures": fx}
    # напор насоса скважины
    H_dyn = 25.0; H_geo = 7.0; H_free = 20.0; H_loss = (dp_in + dp_coll) / 9810 + 5.0 + 3.0
    Hy["pump_well"] = {"H_dyn": H_dyn, "H_geo": H_geo, "H_free": H_free, "H_loss": H_loss, "H_total": H_dyn + H_geo + H_free + H_loss,
                       "Q": Wt["pump"]["Q"]}
    # --- канализация: пропускная способность (Маннинг, n=0,010, наполнение 0,5)
    def q_full(d_mm, i):
        d = d_mm / 1000
        A = math.pi * d * d / 4
        Rh = d / 4
        v = (1 / 0.010) * Rh ** (2 / 3) * i ** 0.5
        return v, v * A * 1000
    v110, Q110 = q_full(104, 0.02)
    v50, Q50 = q_full(46, 0.035)
    Hy["sewer"] = {"v110": v110, "Q110": Q110, "v50": v50, "Q50": Q50, "q_max": 1.6 + 0.3 * 4, "note": "расчётный расход стоков ≈ q_s + 1,6 (унитаз) = 2,1 л/с"}
    return Hy


