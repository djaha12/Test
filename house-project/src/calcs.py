def walls_calc(L):
    W = {}
    L0 = 6.3 - 0.2 - 0.125 + 0.2
    # наружная стена E/W у основания (расчётные нагрузки на 1 м)
    N_ext = (R["roof"]["R_wall"] + 0.375 * L["attic"]["q_d"] * L0 + L["wall_ext"]["g_n"] * 3.3 * 1.1
             + 0.375 * L["floor2"]["q_d"] * L0 + L["wall_ext"]["g_n"] * 3.3 * 1.1)
    W["N_ext_m"] = N_ext
    # самый узкий простенок: восточная стена между ОК-3 (2,4–3,6) и ОК-5 (4,6–5,2): 1,0 м, грузовая длина 2,2 м
    W["pier_w"], W["pier_trib"] = 1.0, 2.2
    W["N_pier_m"] = N_ext * W["pier_trib"] / W["pier_w"]
    R_ext = 1.6e3   # кПа, кладка D400 B2.5 на клею (СП 15 табл. 3 / СТО НААГ)
    lam = 3.0 / 0.4
    phi = 1 - 0.04 * (lam - 4) if lam > 4 else 1.0   # упрощённо для кладки, α=1000 → φ≈0,9
    phi = max(min(phi, 1.0), 0.6)
    e = 0.05
    Ac = 0.4 * (1 - 2 * e / 0.4)
    W["phi"], W["Ac"] = phi, Ac
    W["N_u_ext"] = phi * R_ext * Ac
    W["util_ext"] = W["N_pier_m"] / W["N_u_ext"]
    # внутренняя стена по оси 2
    N_int = (R["roof"]["R_ridge"] + 1.25 * L["attic"]["q_d"] * L0 + L["wall_bear"]["g_n"] * 3.1 * 1.1
             + 1.25 * L["floor2"]["q_d"] * L0 + L["wall_bear"]["g_n"] * 3.0 * 1.1)
    W["N_int_m"] = N_int
    R_int = 2.1e3
    lam_i = 3.0 / 0.25
    phi_i = max(min(1 - 0.04 * (lam_i - 4), 1.0), 0.6)
    W["phi_int"] = phi_i
    W["N_u_int"] = phi_i * R_int * 0.25 * (1 - 2 * 0.02 / 0.25)
    W["util_int"] = N_int / W["N_u_int"]
    # местное смятие под плитой (опирание 300 мм)
    W["sigma_local_ext"] = (0.375 * L["floor2"]["q_d"] * L0) / 0.3 / 1e3
    return W


