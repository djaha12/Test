def f2(x, nd=2):
    return f"{x:.{nd}f}".replace(".", ",")


def bar_area(d):
    return math.pi * d * d / 4


def choose_bars(As_req, options=((10, 250), (10, 200), (12, 250), (12, 200), (12, 150), (14, 200), (14, 150), (16, 200), (16, 150))):
    """подбор стержней на 1 м: (диаметр, шаг) с площадью ≥ As_req"""
    for d, s in options:
        As = bar_area(d) * 1000 / s
        if As >= As_req:
            return d, s, As
    return 16, 100, bar_area(16) * 10


def rc_as(M, b, h0, Rb=14.5, Rs=435.0):
    """Площадь растянутой арматуры прямоугольного сечения (СП 63, п. 8.1.8). M кН·м, b,h0 м → мм²"""
    am = M * 1e3 / (Rb * 1e6 * b * h0 * h0)
    if am > 0.4:
        return None, am, None
    xi = 1 - math.sqrt(1 - 2 * am)
    As = xi * b * h0 * Rb / Rs * 1e6
    return As, am, xi


def rc_mu(As_mm2, b, h0, Rb=14.5, Rs=435.0):
    """Несущая способность по моменту, кН·м"""
    x = As_mm2 * Rs / (Rb * b * 1e3)  # мм
    return As_mm2 * Rs * (h0 * 1e3 - x / 2) / 1e6


