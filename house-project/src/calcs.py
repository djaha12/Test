def foundation(L):
    F = {}
    R0 = 200.0   # кПа, суглинок полутвёрдый (принято; СП 22 прил. Б, табл. Б.3)
    E_soil = 15.0  # МПа (принято)
    F["R0"], F["E_soil"] = R0, E_soil
    F["p_n"], F["p_d"] = L["p_avg_n"], L["p_avg_d"]
    F["util"] = F["p_n"] / R0
    # осадка (упрощённо, схема линейно-деформируемого полупространства, жёсткий штамп)
    b = FOOTPRINT_W + 0.6
    l = FOOTPRINT_D + 0.6
    omega = 0.88  # для l/b≈1,2 (средняя осадка жёсткого прямоугольного штампа)
    sigma_zg = 0.65 * 18.0   # природное давление на уровне подошвы подушки (выемка 0,65 м)
    p_add = max(F["p_n"] - sigma_zg, 0)
    F["p_add"] = p_add
    F["s_mm"] = (1 - 0.3 ** 2) * p_add * b * omega / (E_soil * 1e3) * 1000
    F["s_lim"] = 100.0
    # изгиб плиты как обратного неразрезного перекрытия (верхняя оценка, равномерный отпор)
    q = L["q_net_d"]
    Lsp = 6.3 - 0.2 - 0.125 + 0.3
    F["q_net_d"], F["L_span"] = q, Lsp
    F["M_sup"] = q * Lsp ** 2 / 10    # под стенами (низ растянут)
    F["M_span"] = q * Lsp ** 2 / 14   # в пролёте (верх растянут)
    h0 = 0.30 - 0.05 - 0.007
    F["h0"] = h0
    As_sup, am1, _ = rc_as(F["M_sup"], 1.0, h0)
    As_span, am2, _ = rc_as(F["M_span"], 1.0, h0)
    F["As_sup"], F["As_span"] = As_sup, As_span
    F["mesh"] = (14, 200)
    F["As_mesh"] = bar_area(14) * 1000 / 200
    F["M_u_mesh"] = rc_mu(F["As_mesh"], 1.0, h0)
    F["As_add_axis2"] = (14, 200)   # дополнительные нижние стержни в полосе 2,0 м под осью 2
    F["M_u_axis2"] = rc_mu(2 * F["As_mesh"], 1.0, h0)
    # продавливание/срез под осью 2
    N_line = (L["totals"]["floor2"][1] * 1.25 * 0.5 + L["totals"]["attic"][1] * 1.25 * 0.5 + L["totals"]["roof"][1] * 0.5) / 15.2 \
             + L["totals"]["walls_bear"][1] / 15.2
    F["N_axis2_line"] = N_line
    Q = N_line / 2
    Qb_min = 0.5 * 1.05e3 * 1.0 * (0.6 - 0.05)   # с ребром h0≈0,55
    F["Q_axis2"], F["Qb_min"] = Q, Qb_min
    # объёмы
    F["V_concrete"] = L["areas"]["A_raft"] * 0.3 + (L["areas"]["per"] * 0.4 + 15.2 * 0.25) * 0.3
    F["steel_t"] = (4 * F["As_mesh"] * 1e-6 * 7850 * L["areas"]["A_raft"] + 2.0 * 15.2 * 2 * F["As_mesh"] * 1e-6 * 7850) / 1000 * 1.12 \
                   + (L["areas"]["per"] + 15.2) * (4 * bar_area(12) + 2 * bar_area(8) * 1000 / 300 * 1.2) * 1e-6 * 7850 / 1000
    return F


