def roof_calc(L):
    Rf = {}
    q_h_d = L["roof"]["q_d"] * ROOF["rafter_step"]
    q_h_n = L["roof"]["q_n"] * ROOF["rafter_step"]
    Rf["q_d"], Rf["q_n"] = q_h_d, q_h_n
    L1 = ROOF["purlin_x"][0] - (-0.1)   # 3,1 (от мауэрлата до прогона)
    L2 = ROOF["ridge_x"] - ROOF["purlin_x"][0]   # 3,3
    Rf["L1"], Rf["L2"] = L1, L2
    Lmax = max(L1, L2)
    Rf["M"] = q_h_d * Lmax ** 2 / 8
    b, h = ROOF["rafter"]
    W = b * h * h / 6
    Rf["sigma"] = Rf["M"] / W / 1e3   # МПа
    Rf["R_bend"] = 13.0
    Rf["util_rafter"] = Rf["sigma"] / Rf["R_bend"]
    Ls = Lmax / ROOF["cos"]
    qn_norm = q_h_n * ROOF["cos"] ** 2
    I = b * h ** 3 / 12
    E = 10e6   # кН/м²
    Rf["f_mm"] = 0.00541 * qn_norm * Ls ** 4 / (E * I) * 1000
    Rf["f_lim_mm"] = Ls / 200 * 1000
    # реакции (на 1 м длины прогона/стены)
    Rf["R_int_purlin"] = 1.25 * L["roof"]["q_d"] * (L1 + L2) / 2
    Rf["R_ridge"] = 2 * 0.375 * L["roof"]["q_d"] * L2
    Rf["R_wall"] = 0.375 * L["roof"]["q_d"] * L1 + L["roof"]["q_d"] * ROOF["eaves_overhang"]
    # прогон 100×250 с подкосами (расчётный пролёт ≈ 1,8 м) и без (3,0 м)
    pb, ph = ROOF["purlin"]
    Wp = pb * ph * ph / 6
    Rf["M_purlin_3"] = Rf["R_int_purlin"] * ROOF["post_step"] ** 2 / 8
    Rf["sigma_purlin_3"] = Rf["M_purlin_3"] / Wp / 1e3
    Rf["M_purlin_strut"] = Rf["R_int_purlin"] * 1.8 ** 2 / 8
    Rf["sigma_purlin_strut"] = Rf["M_purlin_strut"] / Wp / 1e3
    # стойки
    P = Rf["R_int_purlin"] * ROOF["post_step"]
    Rf["P_post"] = P
    Rf["P_ridge_post"] = Rf["R_ridge"] * ROOF["post_step"]
    zb = roof_z(ROOF["ridge_x"]) - ROOF["rafter"][1] / ROOF["cos"] - ph
    Rf["l_ridge_post"] = zb - 6.65
    zb2 = roof_z(ROOF["purlin_x"][0]) - ROOF["rafter"][1] / ROOF["cos"] - ph
    Rf["l_int_post"] = zb2 - 6.65
    pw, pd = ROOF["post"]
    A = pw * pd
    r = pw / math.sqrt(12)
    lam = Rf["l_ridge_post"] / r
    phi = 3000 / lam ** 2 if lam > 70 else 1 - 0.8 * (lam / 100) ** 2
    Rf["lam_ridge"], Rf["phi_ridge"] = lam, phi
    Rf["N_u_ridge"] = phi * 13e3 * A
    lam2 = Rf["l_int_post"] / r
    phi2 = 3000 / lam2 ** 2 if lam2 > 70 else 1 - 0.8 * (lam2 / 100) ** 2
    Rf["lam_int"], Rf["phi_int"] = lam2, phi2
    Rf["N_u_int"] = phi2 * 13e3 * A
    Rf["N_u_bearing"] = 3.0e3 * pw * pd   # смятие поперёк волокон лежня
    # ветер (отсос) — проверка на отрыв
    w0 = CLIMATE["w_0"]
    Rf["w_uplift"] = w0 * 0.75 * 0.7 * 1.4
    Rf["uplift_per_rafter"] = Rf["w_uplift"] * ROOF["rafter_step"] * 3.5
    Rf["weight_per_rafter"] = L["roof"]["g_n"] * ROOF["cos"] * ROOF["rafter_step"] * 3.5 * 0.9
    return Rf


