def thermal():
    T = {}
    c = CLIMATE
    GSOP = (c["t_int"] - c["t_hp"]) * c["z_hp"]
    T["GSOP"] = GSOP
    T["R_req"] = {"wall": 0.00035 * GSOP + 1.4, "attic": 0.0005 * GSOP + 2.2, "floor": 0.00045 * GSOP + 1.9,
                  "window": 0.000075 * GSOP + 0.15}
    # стена
    layers_wall = [("Штукатурка гипсовая 15 мм", 0.015, 0.35), ("Газобетон D400, 400 мм (λ_Б=0,117)", 0.40, 0.117),
                   ("Штукатурка тонкослойная 10 мм", 0.010, 0.35)]
    R0 = 1 / 8.7 + sum(d / l for _, d, l in layers_wall) + 1 / 23
    r = 0.85
    T["wall"] = {"layers": layers_wall, "R0": R0, "r": r, "R_pr": R0 * r, "ok": R0 * r >= T["R_req"]["wall"]}
    layers_attic = [("Ж/б плита 200 мм", 0.2, 1.92), ("Пароизоляция", 0.0005, 0.3), ("Минвата 250 мм (λ_Б=0,045)", 0.25, 0.045)]
    R0a = 1 / 8.7 + sum(d / l for _, d, l in layers_attic) + 1 / 12
    T["attic"] = {"layers": layers_attic, "R0": R0a, "r": 0.95, "R_pr": R0a * 0.95, "ok": R0a * 0.95 >= T["R_req"]["attic"]}
    # пол по грунту (зональный метод)
    R_ins = 0.15 / 0.041 + 0.10 / 0.034 + 0.3 / 1.92 + 0.12 / 0.93
    zones = [("I (0–2 м)", 2.1), ("II (2–4 м)", 4.3), ("III (4–6 м)", 8.6), ("IV (>6 м)", 14.2)]
    Wd, Dd = FOOTPRINT_W, FOOTPRINT_D
    areas = []
    prev = Wd * Dd
    for i, (nm, Rz) in enumerate(zones):
        inner_w, inner_d = max(Wd - 4 * (i + 1), 0), max(Dd - 4 * (i + 1), 0)
        inner = inner_w * inner_d
        areas.append((nm, Rz, prev - inner, Rz + R_ins))
        prev = inner
    T["floor"] = {"R_ins": R_ins, "zones": areas, "AR": sum(a / Rt for _, _, a, Rt in areas)}
    T["window"] = {"R": MATERIALS["glazing"]["R"], "ok": MATERIALS["glazing"]["R"] >= T["R_req"]["window"]}
    T["door"] = {"R": 0.8, "garage": 1.0}
    # удельная теплозащитная характеристика
    A_win = window_area()
    A_doors = ext_door_area()
    per = 2 * (12.6 + 15.6)
    A_wall = per * 6.5 - A_win - A_doors
    A_att = 12.8 * 15.8
    V = FOOTPRINT_W * FOOTPRINT_D * 6.5
    AR_wall = A_wall / T["wall"]["R_pr"]
    AR_win = A_win / T["window"]["R"]
    AR_door = 3.0 * 2.4 / 1.0 + 1.0 * 2.1 / 0.8 + (2.4 * 2.3 + 3.0 * 2.3) / 0.72
    AR_att = A_att / T["attic"]["R_pr"] * 0.9
    AR_floor = T["floor"]["AR"]
    T["AR"] = {"wall": AR_wall, "win": AR_win, "door": AR_door, "attic": AR_att, "floor": AR_floor}
    T["AR_sum"] = AR_wall + AR_win + AR_door + AR_att + AR_floor
    T["V"] = V
    T["k_ob"] = T["AR_sum"] / V
    T["k_ob_norm"] = 0.40
    T["A"] = {"wall": A_wall, "win": A_win, "door": A_doors, "attic": A_att}
    return T


