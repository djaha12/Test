def heating(T):
    H = {}
    dt = CLIMATE["t_int"] - CLIMATE["t_ext"]
    H["dt"] = dt
    H["Q_tr"] = T["AR_sum"] * dt * 1.05 / 1000   # кВт, +5% на ориентацию
    V_int = 340.6 * 3.0
    H["V_int"] = V_int
    H["n"] = 0.5
    H["Q_vent"] = 0.34 * H["n"] * V_int * dt / 1000
    H["Q_vent_hrv"] = H["Q_vent"] * (1 - 0.75)
    H["Q_total"] = H["Q_tr"] + H["Q_vent"]
    H["Q_total_hrv"] = H["Q_tr"] + H["Q_vent_hrv"]
    H["Q_dhw"] = 25.0
    H["boiler_kW"] = 32.0
    # годовое потребление
    E = (T["AR_sum"] + 0.34 * H["n"] * V_int) * T["GSOP"] * 24 / 1000
    H["E_year_gross"] = E
    H["E_year"] = E * 0.75      # с учётом бытовых и солнечных теплопоступлений
    H["E_spec"] = H["E_year"] / 340.6
    H["gas_m3"] = H["E_year"] / (9.45 * 0.95) + 3000 / 9.45   # + ГВС ~3000 кВт·ч
    # по помещениям (упрощённо): доля по площади наружных ограждений
    rooms = []
    for fl in (1, 2):
        for r in ROOMS[fl]:
            a = room_area(r)
            rects = r["rects"]
            # длины наружных стен помещения
            ext_len = 0.0
            win_a = 0.0
            for (x1, y1, x2, y2) in rects:
                if abs(x1 - EXT_INNER[0]) < 0.01: ext_len += y2 - y1
                if abs(x2 - EXT_INNER[2]) < 0.01: ext_len += y2 - y1
                if abs(y1 - EXT_INNER[1]) < 0.01: ext_len += x2 - x1
                if abs(y2 - EXT_INNER[3]) < 0.01: ext_len += x2 - x1
            for s, a1, a2, h, sill, tag in WINDOWS[fl]:
                for (x1, y1, x2, y2) in rects:
                    if s in ("N", "S") and (abs((y1 if s == "N" else y2) - (EXT_INNER[1] if s == "N" else EXT_INNER[3])) < 0.01) and a1 >= x1 - 0.01 and a2 <= x2 + 0.01:
                        win_a += (a2 - a1) * h
                    if s in ("W", "E") and (abs((x1 if s == "W" else x2) - (EXT_INNER[0] if s == "W" else EXT_INNER[2])) < 0.01) and a1 >= y1 - 0.01 and a2 <= y2 + 0.01:
                        win_a += (a2 - a1) * h
            if fl == 1:
                for s, a1, a2, h, tag, kind in EXT_DOORS[1]:
                    for (x1, y1, x2, y2) in rects:
                        if s == "N" and abs(y1 - EXT_INNER[1]) < 0.01 and a1 >= x1 - 0.01 and a2 <= x2 + 0.01:
                            win_a += (a2 - a1) * h
                        if s == "S" and abs(y2 - EXT_INNER[3]) < 0.01 and a1 >= x1 - 0.01 and a2 <= x2 + 0.01:
                            win_a += (a2 - a1) * h
            wall_a = max(ext_len * 3.0 - win_a, 0)
            t_in = 10.0 if r["heated"] == "garage" else (24.0 if r.get("wet") and "Санузел" in r["name"] or "Ванная" in r["name"] else 20.0)
            dti = t_in - CLIMATE["t_ext"]
            q = (wall_a / T["wall"]["R_pr"] + win_a / 0.72) * dti
            if fl == 1:
                q += a / 9.0 * dti * (1.0 if ext_len > 0 else 0.5)
            else:
                q += a / T["attic"]["R_pr"] * dti * 0.9
            q_v = 0.34 * 0.5 * a * 3.0 * dti
            q_tot = (q + q_v) * 1.05
            rooms.append({"n": r["n"], "name": r["name"], "area": a, "t_in": t_in, "wall_a": wall_a, "win_a": win_a, "Q_W": q_tot,
                          "q_Wm2": q_tot / a, "floor": fl, "garage": r["heated"] == "garage"})
    H["rooms"] = rooms
    H["Q_rooms_sum"] = sum(x["Q_W"] for x in rooms) / 1000
    # тёплый пол: шаг 150 (100 в санузлах), макс. петля 100 м
    loops = []
    for x in rooms:
        if x["garage"]:
            continue
        step = 0.10 if x["q_Wm2"] > 70 else 0.15
        length = x["area"] / step * 1.05 + 8
        n = math.ceil(length / 100)
        loops.append({"n": x["n"], "name": x["name"], "area": x["area"], "step": step, "length": length, "loops": n,
                      "q": x["q_Wm2"], "floor": x["floor"]})
    H["ufh"] = loops
    H["pipe_total"] = sum(l["length"] for l in loops)
    H["loops_1"] = sum(l["loops"] for l in loops if l["floor"] == 1)
    H["loops_2"] = sum(l["loops"] for l in loops if l["floor"] == 2)
    return H


