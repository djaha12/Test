def slab_calc(L):
    S = {}
    Lc = 6.3 - 0.2 - 0.125          # 5,975 в свету
    L0 = Lc + 0.2                    # расчётный пролёт
    S["L0"] = L0
    h = 0.20
    h0 = h - 0.025 - 0.006
    S["h0"] = h0
    for key, name in (("floor2", "междуэтажное"), ("attic", "чердачное")):
        q = L[key]["q_d"]
        qn = L[key]["q_n"]
        M_sup = q * L0 ** 2 / 8
        M_span = 9 / 128 * q * L0 ** 2
        extra_sup = extra_span = 0.0
        if key == "attic":
            # сосредоточенные нагрузки от стоек кровли (x=3,0 и 9,6 — середина пролёта), b_eff=3,0 м
            P = R["roof"]["R_int_purlin"] * ROOF["post_step"]
            extra_span = 0.156 * P * L0 / 3.0
            extra_sup = 0.188 * P * L0 / 3.0
            S["P_post"] = P
        M_sup_t, M_span_t = M_sup + extra_sup, M_span + extra_span
        As_sup, am_s, _ = rc_as(M_sup_t, 1.0, h0)
        As_span, am_p, _ = rc_as(M_span_t, 1.0, h0)
        d1, s1, A1 = choose_bars(As_sup)
        d2, s2, A2 = choose_bars(As_span, options=((12, 200), (12, 150), (14, 200), (14, 150)))
        # прогиб (2-пролётная, квазипостоянная нагрузка, с учётом трещин и ползучести)
        q_qp = qn - (1.5 if key == "floor2" else 0.7) * 0.65
        Eb = 30e3 * 1e3  # кН/м²
        I = 1.0 * h ** 3 / 12
        EI_eff = Eb * I * 0.5 / (1 + 2.0)
        f = 0.00541 * q_qp * L0 ** 4 / EI_eff
        S[key] = {"name": name, "q_d": q, "q_n": qn, "M_sup": M_sup_t, "M_span": M_span_t, "As_sup": As_sup, "As_span": As_span,
                  "sup_bars": (d1, s1, A1), "span_bars": (d2, s2, A2), "M_u_sup": rc_mu(A1, 1.0, h0), "M_u_span": rc_mu(A2, 1.0, h0),
                  "f_mm": f * 1000, "f_lim_mm": L0 / 200 * 1000, "h_min": L0 / 30}
    return S


