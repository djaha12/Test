PART_T = {"part": 0.10, "part150": 0.15, "fire": 0.20}


def partitions():
    """Длины и объёмы перегородок по фактической толщине (по прямоугольникам стен модели)."""
    L = {"part": 0.0, "part150": 0.0, "fire": 0.0}
    for fl in (1, 2):
        for w in WALLS[fl]:
            if w["kind"] in L:
                x1, y1, x2, y2 = w["rect"]
                L[w["kind"]] += max(x2 - x1, y2 - y1)
    h = 3.0
    return {"L100": L["part"], "L150": L["part150"], "L200": L["fire"],
            "V100": L["part"] * PART_T["part"] * h, "V150": L["part150"] * PART_T["part150"] * h, "V200": L["fire"] * PART_T["fire"] * h}


