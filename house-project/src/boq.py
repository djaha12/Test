    md = ["# Ведомость объёмов работ и ориентировочная стоимость строительства", "",
          "> Цены — ориентировочные (материалы + работа), уровень Московской области 2025–2026 гг., точность ±20 %. Не заменяет смету по рабочему проекту и коммерческие предложения подрядчиков. НДС и прибыль генподрядчика (10–15 %) при подрядном способе — сверх указанного.", ""]
