def gantt_svg(path):
    sh = Sheet("A3", code="ГР-1", title="Календарный график строительства", scale_txt="б/м", sheet_no=1, sheets_total=1)
    sh.ptext(30, 18, "Календарный график строительства (ориентировочно, старт — март)", size=4.2, anchor="start", weight="bold")
    x0, y0 = 150, 34
    wk = 3.9   # мм на неделю
    total_w = 60
    months = ["мар", "апр", "май", "июн", "июл", "авг", "сен", "окт", "ноя", "дек", "янв", "фев", "мар", "апр", "май"]
    for m in range(15):
        x = x0 + m * 4.33 * wk
        sh.pline(x, y0 - 6, x, y0 + len(SCHEDULE) * 8 + 2, w="thin", color="#bbb")
        sh.ptext(x + 2.1 * wk, y0 - 3, months[m], size=2.0)
        if m >= 9 and m <= 11:
            sh.prect(x, y0, 4.33 * wk, len(SCHEDULE) * 8, fill="#dbe8f5", stroke=None, opacity=0.6)
    sh.ptext(x0 + 10.3 * 4.33 * wk, y0 - 8, "зимний период — внутренние работы", size=1.9)
    for i, (name, s, d, note) in enumerate(SCHEDULE):
        y = y0 + i * 8
        sh.ptext(x0 - 4, y + 4, name, size=1.9, anchor="end")
        col = "#1a5fb4" if i < 10 else ("#2a8a3a" if i < 15 else "#e08a00")
        sh.prect(x0 + s * wk, y + 1.5, d * wk, 5, fill=col, stroke=None, opacity=0.85)
        sh.ptext(x0 + (s + d) * wk + 2, y + 4, f"{d} нед." + (f" ({note})" if note else ""), size=1.7, anchor="start")
    sh.prect(x0, y0, total_w * wk, len(SCHEDULE) * 8, fill="none", stroke="#000", sw="thin")
    yy = y0 + len(SCHEDULE) * 8 + 10
    for col, txt in (("#1a5fb4", "коробка и тепловой контур"), ("#2a8a3a", "инженерные системы"), ("#e08a00", "отделка, благоустройство, сдача")):
        sh.prect(x0, yy - 2, 8, 4, fill=col, stroke=None); sh.ptext(x0 + 11, yy, txt, size=2.0, anchor="start"); yy += 5
    end = max(s + d for _, s, d, _ in SCHEDULE)
    sh.ptext(30, yy + 4, f"Общая продолжительность ≈ {end} недель (≈ {end / 4.33:.0f} месяцев) при непрерывном финансировании и бригаде 6–8 человек на общестроительных работах.", size=2.2, anchor="start")
    sh.ptext(30, yy + 9, "Критический путь: фундамент → стены → перекрытия → кровля → тепловой контур → стяжки/штукатурка → чистовая отделка. Инженерные сети и благоустройство — параллельно.", size=2.0, anchor="start")
    sh.save(path)
    return end


def md_money(x):
    return f"{x:,.0f}".replace(",", " ")


