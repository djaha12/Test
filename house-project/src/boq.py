           "- Кровля: металлочерепица вместо фальца — −25…30 % по разделу 5 (≈ −0,5 млн ₽).",
           "- Окна: без ламинации, профиль 60 мм — −20 % по окнам; порталы — заменить на двери с боковыми глухими окнами.",
           "- Отделка чистовая — самая вариативная позиция (±50 %): указан уровень «средний+».",
