    md.append("| Группа | Сумма, ₽ | Доля | ₽/м² общей площади |")
    md.append("|---|---:|---:|---:|")
    for g, keys in groups.items():
        v = sum(sec_sum[k] for k in set(keys))
        md.append(f"| {g} | {md_money(v)} | {v / subtotal * 100:.0f} % | {md_money(v / S['area_total'])} |")
    md.append(f"| **Всего с непредвиденными** | **{md_money(total)}** | 100 % | **{md_money(total / S['area_total'])}** (≈ {md_money(total / S['building_area_gross'])} ₽/м² по наружному обмеру) |")
