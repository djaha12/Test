def md_money(x):
    return f"{x:,.0f}".replace(",", " ")


def fq(x):
    if isinstance(x, float) and not float(x).is_integer():
        return f"{x:,.1f}".replace(",", " ").replace(".", ",")
    return f"{x:,.0f}".replace(",", " ")


