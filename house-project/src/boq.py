def wall_lengths():
    part100 = part200 = 0.0
    for fl in (1, 2):
        for w in WALLS[fl]:
            x1, y1, x2, y2 = w["rect"]
            L = max(x2 - x1, y2 - y1)
            if w["kind"] == "part":
                part100 += L
            elif w["kind"] == "fire":
                part200 += L
    return part100, part200


