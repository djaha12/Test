def _prepay(sec, name):
    """(доля, за сколько недель до начала этапа) — авансы за заказные изделия и оборудование."""
    if sec.startswith("6.") and not any(k in name for k in ("внутренние", "противопожарные")):
        return (0.6, 6)      # окна, порталы, ворота: 60 % при заказе за 6 недель
    if any(k in name for k in ("Котёл", "Бойлер", "Станция биологической", "Водоподготовка", "Ворота откатные", "Раздвижные")):
        return (0.5, 4)
    if "Отделка лестницы" in name or "Паркетная" in name:
        return (0.5, 5)
    return None


def cashflow(rows, contingency):
    end = max(s + d for _, s, d, _ in SCHEDULE)
    n_m = math.ceil(end / WPM)
    weeks = [0.0] * (end + 1)
    task_week = [[0.0] * (end + 1) for _ in range(len(SCHEDULE) + 1)]

    def put(task, amount, s, d, pre=None):
        if pre:
            frac, wb = pre
            w0 = max(0, s - wb)
            weeks[w0] += amount * frac; task_week[task][w0] += amount * frac
            amount *= (1 - frac)
        for w in range(s, min(s + d, end)):
            weeks[w] += amount / d; task_week[task][w] += amount / d

    for sec, name, unit, qty, price, total in rows:
        t = _tasks_for(sec, name)
        pre = _prepay(sec, name)
        if t == "spread":
            put(N_SPREAD, total, 2, end - 2)
        else:
            for ti, share in t:
                _, s, d, _ = SCHEDULE[ti]
                put(ti, total * share, s, d, pre)
    base_sum = sum(weeks)
    months = []
    for m in range(n_m):
        w1, w2 = int(round(m * WPM)), int(round((m + 1) * WPM))
        amt = sum(weeks[w1:w2])
        amt_c = amt * (1 + contingency / base_sum)
        by_task = sorted(((sum(task_week[t][w1:w2]), t) for t in range(len(SCHEDULE) + 1)), reverse=True)
        works = [SHORT[t] for a, t in by_task if a > 0.02 * max(amt, 1)][:4]
        months.append({"m": m, "name": MONTHS[m], "amount": amt_c, "works": works, "weeks": (w1, w2)})
    cum = 0.0
    for mo in months:
        cum += mo["amount"]; mo["cum"] = cum
    return months


